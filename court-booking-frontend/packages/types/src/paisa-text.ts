export const PAISA_TEXT: Record<PaisaLang, Record<PaisaKey, string>> = { ru: RU, en: EN };

export function paisaT(lang: PaisaLang, key: PaisaKey, vars?: Record<string, string | number>): string {
  const template = PAISA_TEXT[lang]?.[key] ?? RU[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

