export function themeCss(): string {
  const lines: string[] = [HEADER, "/* Imported by apps/web/app/globals.css. Utilities: bg-fl-*, text-fl-*, rounded-fl-*, shadow-fl-*, font-fl-*. */", "", "@theme {"];
  for (const [k, v] of Object.entries(palette)) lines.push(`  --color-fl-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(alpha)) lines.push(`  --color-fl-a-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(radius)) lines.push(`  --radius-fl-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(shadow)) lines.push(`  --shadow-fl-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(space)) lines.push(`  --spacing-fl-${k}: ${v}px;`);
  lines.push(`  --font-fl-display: ${fontFamily.web.display};`);
  lines.push(`  --font-fl-body: ${fontFamily.web.body};`);
  lines.push(`  --ease-fl: ${motion.easing};`);
  lines.push("}");
  lines.push("");
  lines.push("/* Role theme: every fl component sets data-fl-role on its own root (from RoleProvider); default is player. */");
  for (const r of ["player", "owner"] as Role[]) {
    lines.push(r === "player" ? `:root, [data-fl-role="player"] {` : `[data-fl-role="owner"] {`);
    for (const [k, v] of roleVars(role[r])) lines.push(`  --fl-${k}: ${v};`);
    lines.push(`  --fl-motion-fast: ${motion.fast}ms;`);
    lines.push(`  --fl-motion-base: ${motion.base}ms;`);
    lines.push("}");
  }
  lines.push("");
  lines.push("@theme inline {");
  for (const [util, v] of ROLE_COLOR_UTILS) lines.push(`  --color-fl-${util}: var(--fl-${v});`);
  lines.push("  --shadow-fl-role-primary: var(--fl-primary-shadow);");
  lines.push("}");
  lines.push("");
  lines.push("@keyframes fl-toast-in { from { opacity: 0; transform: translateY(8px); } to { opacity: 1; transform: none; } }");
  lines.push("");
  lines.push("@media (prefers-reduced-motion: reduce) {");
  lines.push("  [data-fl-role] { --fl-motion-fast: 0ms; --fl-motion-base: 0ms; }");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}
