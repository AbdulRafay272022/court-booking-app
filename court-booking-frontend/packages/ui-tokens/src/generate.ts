/**
 * Builds the two generated artefacts from the TS tokens (pure string builders, so a test can check the committed files are
 * in sync): generated/tailwind.cjs (mobile NativeWind config) and generated/theme.css (web Tailwind 4 @theme + role vars).
 * Regenerate with `npm run generate --workspace=@court-booking/ui-tokens` after editing tokens.ts / roles.ts.
 */
import { alpha, fontFamily, motion, palette, radius, shadow, space } from "./tokens";
import { role, type Role, type RoleTheme } from "./roles";

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const HEADER = "/* GENERATED by packages/ui-tokens/scripts/generate.ts from src/tokens.ts + src/roles.ts. Do not edit by hand. */";

/** Flat colour map for Tailwind (`bg-fl-night`, `text-fl-orange-deep`, `border-fl-line-strong`). */
export function tailwindColors(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(palette)) out[kebab(k)] = v;
  for (const [k, v] of Object.entries(alpha)) out[`a-${kebab(k)}`] = v;
  for (const r of ["player", "owner"] as Role[]) {
    const t = role[r];
    out[`${r}-primary`] = t.primary.bg;
    out[`${r}-on-primary`] = t.primary.fg;
    out[`${r}-selected`] = t.selected.bg;
    out[`${r}-on-selected`] = t.selected.fg;
    out[`${r}-selected-border`] = t.selected.border;
    out[`${r}-link`] = t.link;
    out[`${r}-hero`] = t.hero.bg;
  }
  return out;
}

export function tailwindCjs(): string {
  const fonts: Record<string, string[]> = {};
  for (const [k, v] of Object.entries(fontFamily.mobile)) fonts[`fl-${kebab(k)}`] = [v];
  const body = {
    colors: tailwindColors(),
    fontFamily: fonts,
    borderRadius: Object.fromEntries(Object.entries(radius).map(([k, v]) => [`fl-${kebab(k)}`, `${v}px`])),
  };
  return `${HEADER}\n// Used by apps/mobile/tailwind.config.js: theme.extend.colors.fl, fontFamily, borderRadius.\nmodule.exports = ${JSON.stringify(body, null, 2)};\n`;
}

function roleVars(t: RoleTheme): [string, string][] {
  return [
    ["primary-bg", t.primary.bg],
    ["primary-fg", t.primary.fg],
    ["primary-shadow", t.primary.shadow],
    ["tab-active-bg", t.tabActive.bg],
    ["tab-active-fg", t.tabActive.fg],
    ["tab-idle-fg", t.tabIdle.fg],
    ["selected-bg", t.selected.bg],
    ["selected-fg", t.selected.fg],
    ["selected-border", t.selected.border],
    ["slot-selected-bg", t.slotSelected.bg],
    ["slot-selected-fg", t.slotSelected.fg],
    ["slot-selected-border", t.slotSelected.border],
    ["slot-range-bg", t.slotInRange.bg],
    ["slot-range-fg", t.slotInRange.fg],
    ["slot-range-border", t.slotInRange.border],
    ["hero-bg", t.hero.bg],
    ["hero-fg", t.hero.fg],
    ["hero-muted", t.hero.fgMuted],
    ["hero-image", t.hero.gradient ?? "none"],
    ["link", t.link],
    ["accent", t.accentText],
    ["focus", t.focusBorder],
    ["control-on-bg", t.control.onBg],
    ["control-on-fg", t.control.onFg],
    ["switch-on", t.switchOn],
    ["ring", t.ring],
    ["ring-on-hero", t.ringOnHero],
    ["badge-bg", t.badge.bg],
    ["badge-fg", t.badge.fg],
    ["gutter", `${t.gutter}px`],
  ];
}

