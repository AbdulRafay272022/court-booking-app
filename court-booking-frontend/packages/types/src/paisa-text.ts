/** The pill tone of a money status (text + colour, never colour alone). */
export function moneyStatusTone(s: MoneyStatus): "open" | "waiting" | "danger" | "neutral" | "info" {
  switch (s) {
    case "paid_full":
    case "cancel_clear":
      return "open";
    case "part_paid":
    case "unpaid":
    case "attendance_pending":
    case "advance_paid":
      return "waiting";
    case "refund_due":
    case "cancel_refund":
    case "disputed":
      return "danger";
    case "noshow_kept":
    case "cancel_kept":
      return "neutral";
    default:
      return "info";
  }
}
